-- Adapted from spring-projects/spring-petclinic, src/main/resources/db/postgres/schema.sql
-- Apache-2.0. Secondary indexes omitted as in Kahvic et al. (2024).
DROP TABLE IF EXISTS visits, pets, owners, types, vet_specialties, specialties, vets CASCADE;

CREATE TABLE vets (
  id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  first_name TEXT,
  last_name TEXT
);
CREATE TABLE specialties (
  id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name TEXT
);
CREATE TABLE vet_specialties (
  vet_id INT NOT NULL REFERENCES vets(id),
  specialty_id INT NOT NULL REFERENCES specialties(id),
  UNIQUE (vet_id, specialty_id)
);
CREATE TABLE types (
  id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name TEXT
);
CREATE TABLE owners (
  id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  first_name TEXT,
  last_name TEXT,
  address TEXT,
  city TEXT,
  telephone TEXT
);
CREATE TABLE pets (
  id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name TEXT,
  birth_date DATE,
  type_id INT NOT NULL REFERENCES types(id),
  owner_id INT REFERENCES owners(id)
);
CREATE TABLE visits (
  id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  pet_id INT REFERENCES pets(id),
  visit_date DATE,
  description TEXT
);
